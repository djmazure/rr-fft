"""Generate hard-coded golden vectors for the cocotb contract tests.

Writes sim/cocotb/tests/fft_goldens.py — committed, never regenerated at
test runtime (ROUTERTL-002: tests attack with hard-coded expectations).
Run from the repo root:  python model/gen_golden.py
"""

from pathlib import Path
import random

from rr_fft_oracle import RrFftOracle

LOG2_N = 8
SCH = [2, 2, 2, 2]
SEEDS = (0xF17, 0xF18)

o = RrFftOracle(LOG2_N, data_width=24, twiddle_width=24)
frames: list[list[tuple[int, int]]] = []

frames.append([(0x400000, -0x1000)] + [(0, 0)] * (o.n - 1))  # impulse
for seed in SEEDS:
    rng = random.Random(seed)
    lim = 1 << 21  # 2-bit headroom keeps the [2,2,2,2] schedule overflow-free
    frames.append([(rng.randrange(-lim, lim), rng.randrange(-lim, lim))
                   for _ in range(o.n)])

expected = []
for f in frames:
    r = o.run(f, scale_schedule=SCH, scaled=True)
    assert not r.overflow
    expected.append(r.data)

# Round-trip goldens (FFT-REQ-007): drive frame 1's SPECTRUM back through
# the core in inverse mode, schedule [0,0,0,0] — the unscaled-equivalent
# growth exactly undoes the forward 1/N, reconstructing the input within
# truncation noise. Verified here at generation time.
INV_SCH = [0, 0, 0, 0]
inv_in = expected[1]
r_inv = o.run(inv_in, inverse=True, scale_schedule=INV_SCH, scaled=True)
assert not r_inv.overflow, "inverse golden overflows — pick a wider schedule"
worst = max(max(abs(g - x) for g, x in zip(got, orig))
            for got, orig in zip(r_inv.data, frames[1]))
assert worst <= 1 << 10, f"round-trip error {worst} suspiciously large"
print(f"round-trip max |err| vs original input: {worst} LSB")

# REQ-004 goldens: frame 2 under a DIFFERENT schedule ([3,2,2,2], config
# word 0x157) — a mid-frame config write must NOT change frame 1's output
# (still [2,2,2,2]) and MUST apply at frame 2's boundary.
SCH_B = [3, 2, 2, 2]
r_b = o.run(frames[2], scale_schedule=SCH_B, scaled=True)
assert not r_b.overflow
assert r_b.data != expected[2], "schedule B must change the output"

# Unscaled goldens (FFT-REQ-002, the G_HAS_SCALING=false build — the
# reference deployment runs unscaled INVERSE). Full-scale 24-bit input; output
# grows to 33 bits per the oracle-proven width plan.
rng = random.Random(0xF19)
UNSCALED_IN = [(rng.randrange(-(1 << 23), 1 << 23),
                rng.randrange(-(1 << 23), 1 << 23)) for _ in range(o.n)]
r_ufwd = o.run(UNSCALED_IN)
r_uinv = o.run(UNSCALED_IN, inverse=True)

out = Path(__file__).resolve().parents[1] / "sim/cocotb/tests/fft_goldens.py"
with out.open("w") as fh:
    fh.write('"""AUTO-GENERATED by model/gen_golden.py — do not hand-edit.\n\n'
             "Oracle-derived goldens: 256-pt, 24-bit, forward, scaled\n"
             f"schedule {SCH} (config word 0x155). Frame 0 = impulse,\n"
             f"frames 1-2 = random seeds {[hex(s) for s in SEEDS]}.\n"
             '"""\n\n')
    fh.write(f"LOG2_N = {LOG2_N}\nCONFIG_WORD = 0x155\n\n")
    fh.write(f"IN_FRAMES = {frames!r}\n\n")
    fh.write(f"EXPECTED = {expected!r}\n\n")
    fh.write("# schedule B (config-boundary test): fwd, sch [3,2,2,2]\n")
    fh.write("CONFIG_WORD_B = 0x157\n")
    fh.write(f"EXPECTED_B_FRAME2 = {r_b.data!r}\n\n")
    fh.write("# inverse mode (fwd=0), schedule [0,0,0,0]\n")
    fh.write("INV_CONFIG_WORD = 0x000\n")
    fh.write(f"INV_IN = {inv_in!r}\n\n")
    fh.write(f"INV_EXPECTED = {r_inv.data!r}\n\n")
    fh.write("# unscaled build (G_HAS_SCALING=false): 33-bit outputs;\n")
    fh.write("# config schedule bits ignored (fwd bit only)\n")
    fh.write("UNSCALED_OW = 33\n")
    fh.write(f"UNSCALED_IN = {UNSCALED_IN!r}\n\n")
    fh.write(f"UNSCALED_FWD_EXPECTED = {r_ufwd.data!r}\n\n")
    fh.write(f"UNSCALED_INV_EXPECTED = {r_uinv.data!r}\n")
print(f"wrote {out} ({len(frames)} fwd + 1 inv + 1 unscaled frame)")

# FFT-REQ-021 fixture vectors (model/vectors/fft_req_021_shim.yml): the five
# standalone packing cases, then every component of the unscaled inverse
# frame above, which test_fft_shim_unscaled.py drives through the shim.
# Re-mint with `rr sim golden mint` after this rewrites the file.
PACKING_CASES = [(0, 0), (1, -1), (1431655765, -715827883),
                 (-4294967296, 4294967295), (-1, 4294967295)]
vec = Path(__file__).resolve().parent / "vectors/fft_req_021_shim.yml"
with vec.open("w", encoding="utf-8", newline="\n") as fh:
    for re_v, im_v in PACKING_CASES + [tuple(s) for s in r_uinv.data]:
        fh.write(f"- core_re: {re_v}\n  core_im: {im_v}\n"
                 "  core_width: 33\n  out_width: 40\n")
print(f"wrote {vec}")
